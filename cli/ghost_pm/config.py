"""Ghost-PM Configuration Loader.

Loads config from multiple sources with this priority:
1. Environment variables (highest)
2. .ghost/config.json (team-specific, auto-generated by ghostpm join)
3. Built-in defaults (Supabase credentials baked in)
"""

